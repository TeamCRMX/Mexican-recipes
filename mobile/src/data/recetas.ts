export type IngredienteReceta = {
  nombre: string;
  cantidad: string;
  categoria: string;
};

export type Receta = {
  id: number;
  nombre: string;
  descripcion: string;
  tiempoMin: number;
  dificultad: 'Fácil' | 'Media' | 'Avanzada';
  ingredientes: IngredienteReceta[];
  utensilios: string[];
  equipos: string[];
  preparacion: string[];
  fuenteUrl?: string;
};

const receta = (
  datos: Omit<Receta, 'ingredientes'> & { ingredientes: string[] },
): Receta => ({
  ...datos,
  ingredientes: datos.ingredientes.map((valor) => {
    const [nombre, cantidad, categoria = 'Despensa'] = valor.split('|');
    return { nombre, cantidad, categoria };
  }),
});

