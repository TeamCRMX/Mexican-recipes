const receta = (
  datos: Omit<Receta, 'ingredientes' | 'categoria' | 'porciones' | 'emoji'> & {
    ingredientes: string[];
    categoria?: CategoriaReceta;
    porciones?: number;
    emoji?: string;
  },
): Receta => ({
  ...datos,
  categoria: datos.categoria ?? CATEGORIA_POR_RECETA[datos.nombre] ?? 'Comida',
  porciones: datos.porciones ?? 4,
  emoji: datos.emoji ?? EMOJI_POR_RECETA[datos.nombre] ?? '🍽️',
  consejo: datos.consejo ?? CONSEJO_POR_RECETA[datos.nombre] ?? 'Prepara y mide los ingredientes antes de comenzar; prueba la sazón al final y ajusta sal y picante a tu gusto.',
  ingredientes: datos.ingredientes.map((valor) => {
    const [nombre, cantidad, categoria = 'Despensa'] = valor.split('|');
    return { nombre, cantidad, categoria };
  }),
});

